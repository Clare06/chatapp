package com.example.demo.dto;

import jakarta.validation.constraints.*;

public class Otp {
    @NotBlank
    private String otp;
    @NotBlank
    @Email
    private String email;

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getOtp() {
        return otp;
    }

    public void setOtp(String otp) {
        this.otp = otp;
    }
}
